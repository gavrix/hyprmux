/// macOS virtual key codes → USB HID keyboard usages (page 0x07), which the
/// simulator's hardware-keyboard path takes.
enum SimulatorKeys {
    static func usage(forKeyCode code: UInt16) -> UInt32? { table[code] }

    /// Modifier keys, for flagsChanged.
    static let modifiers: [UInt16: UInt32] = [
        0x38: 0xE1, 0x3C: 0xE5,  // shift L/R
        0x3B: 0xE0, 0x3E: 0xE4,  // control L/R
        0x3A: 0xE2, 0x3D: 0xE6,  // option L/R
        0x37: 0xE3, 0x36: 0xE7,  // command L/R
        0x39: 0x39,              // caps lock
    ]

    private static let table: [UInt16: UInt32] = {
        var t: [UInt16: UInt32] = [:]
        // Letters: HID a=0x04 ... z=0x1D.
        let letters: [(UInt16, Character)] = [
            (0x00, "a"), (0x0B, "b"), (0x08, "c"), (0x02, "d"), (0x0E, "e"), (0x03, "f"), (0x05, "g"),
            (0x04, "h"), (0x22, "i"), (0x26, "j"), (0x28, "k"), (0x25, "l"), (0x2E, "m"), (0x2D, "n"),
            (0x1F, "o"), (0x23, "p"), (0x0C, "q"), (0x0F, "r"), (0x01, "s"), (0x11, "t"), (0x20, "u"),
            (0x09, "v"), (0x0D, "w"), (0x07, "x"), (0x10, "y"), (0x06, "z"),
        ]
        for (code, ch) in letters { t[code] = 0x04 + UInt32(ch.asciiValue! - Character("a").asciiValue!) }
        // Digits: HID 1=0x1E ... 9=0x26, 0=0x27.
        let digits: [UInt16] = [0x12, 0x13, 0x14, 0x15, 0x17, 0x16, 0x1A, 0x1C, 0x19]  // 1...9
        for (i, code) in digits.enumerated() { t[code] = 0x1E + UInt32(i) }
        t[0x1D] = 0x27  // 0
        let rest: [UInt16: UInt32] = [
            0x24: 0x28, 0x4C: 0x58,  // return, keypad enter
            0x35: 0x29,              // escape
            0x33: 0x2A,              // backspace
            0x30: 0x2B,              // tab
            0x31: 0x2C,              // space
            0x1B: 0x2D, 0x18: 0x2E,  // - =
            0x21: 0x2F, 0x1E: 0x30,  // [ ]
            0x2A: 0x31,              // backslash
            0x29: 0x33, 0x27: 0x34,  // ; '
            0x32: 0x35,              // `
            0x2B: 0x36, 0x2F: 0x37, 0x2C: 0x38,  // , . /
            0x7C: 0x4F, 0x7B: 0x50, 0x7D: 0x51, 0x7E: 0x52,  // right left down up
            0x75: 0x4C,              // forward delete
            0x73: 0x4A, 0x77: 0x4D, 0x74: 0x4B, 0x79: 0x4E,  // home end pgup pgdn
            0x7A: 0x3A, 0x78: 0x3B, 0x63: 0x3C, 0x76: 0x3D, 0x60: 0x3E, 0x61: 0x3F,  // F1-F6
            0x62: 0x40, 0x64: 0x41, 0x65: 0x42, 0x6D: 0x43, 0x67: 0x44, 0x6F: 0x45,  // F7-F12
        ]
        for (k, v) in rest { t[k] = v }
        return t
    }()
}
